# Fields are re-exported wholesale, not topped up, so a real-time init has to be
# revisited while its zarr survives. One lead step of slack covers the case
# where the availability boundary moved between the export and this check.
TRUTH_STALENESS_GRACE_HOURS = 6

# PLAN_EXPLORER.md §4's per-init budget for the eventual four-variable export at
# 0.5°. t2m alone is a quarter of it (§4, "Note this table is the *eventual*
# four-variable budget"), and the current export is 1.0°, so this is a ceiling
# that should be nowhere near hit — it exists to make a resolution or lead-count
# change that blows the repo-growth budget (§7) fail here rather than in git.
FIELDS_BUDGET_BYTES = 24 * 1024 * 1024


def subschema(manifest_schema: dict, name: str) -> dict:
    """A `$defs` entry, wrapped so its internal `$ref`s still resolve.

    The sidecar files are the manifest's `fields` values, so they are validated
    against the same definition rather than a second schema that could drift
    from it. Both the local validator and jsonschema resolve `#/$defs/...`
    against the document root, hence carrying `$defs` along.
    """
    return {"$ref": f"#/$defs/{name}", "$defs": manifest_schema["$defs"]}


# ---------------------------------------------------------------------------
# Layer 3: the decode gate


def encoding_errors(label: str, codes: np.ndarray, source: np.ndarray,
                    scale) -> list[str]:
    """Decode `codes` through `scale` and compare against `source`.

    Three separate claims, because they fail independently:

    - the decoded field is within **half a quantization step** of the source
      everywhere. Round-to-nearest over a scale that contains the data makes
      this an equality bound, not a heuristic one, so exceeding it means the
      scale is not the one the field was encoded with;
    - the reserved missing byte appears at exactly the cells where the source is
      non-finite, and nowhere else — a renderer draws those transparent, so a
      misplaced one silently erases data or paints a hole as a temperature;
    - the shapes match, which catches a transposed or wrongly-regridded field
      before the value comparison reports something incomprehensible.
    """
    errs = []
    if codes.shape != source.shape:
        return [f"{label}: PNG is {codes.shape}, source array is {source.shape}"]

    finite = np.isfinite(source)
    missing = codes == fields.MISSING_BYTE
    if int((missing & finite).sum()):
        n = int((missing & finite).sum())
        errs.append(f"{label}: {n} cell(s) carry the reserved missing byte "
                    f"({fields.MISSING_BYTE}) where the source is finite — that "
                    "data would be drawn as transparent")
    if int((~missing & ~finite).sum()):
        n = int((~missing & ~finite).sum())
        errs.append(f"{label}: {n} non-finite source cell(s) were encoded as "
                    "data rather than the reserved missing byte")

    both = finite & ~missing
    if not both.any():
        return errs
    decoded = fields.dequantize(codes, scale)
    step = fields.quantization_step(scale)
    resid = np.abs(decoded[both] - source[both])
    worst = float(resid.max())
    # Strictly the bound is step/2; the tolerance covers only the float64
    # rounding of the comparison itself, and is ~10 orders of magnitude below a
    # quantization step, so it cannot absorb a real encoding fault.
    if worst > 0.5 * step * (1 + 1e-9) + 1e-12:
        i = int(np.argmax(resid))
        errs.append(
            f"{label}: max |decoded - source| = {worst:.6g} exceeds half the "
            f"quantization step ({0.5 * step:.6g}; scale {list(scale)}, "
            f"{fields.LEVELS} levels). Worst cell: source "
            f"{source[both][i]:.6g}, decoded {decoded[both][i]:.6g}. The PNG "
            "was not encoded with the scale the manifest publishes.")
    return errs


def source_lookup_for_init(cfg: dict, entry: dict, init_time: datetime):
    """A (model, var, kind, lead) -> array callable, or None if unverifiable.

    Regenerates the source arrays with `scoreboard.fields` itself, at the leads
    the export marked `ok` rather than the leads the clock now permits — a
    real-time init's truth window advances between the export and this run, and
    the gate must reproduce what was encoded, not what could be encoded today.
    """
    data = Path(cfg["paths"]["data"])
    models = [m for m in entry["models"]
              if fields.forecast_path(data, m, init_time).exists()]
    if not models:
        return None, entry["models"]
    variables = sorted(entry["variables"])
    leads = entry["leads"]

    ok_leads = sorted({int(h)
                       for v in entry["variables"].values()
                       for h, st in v["error"]["status"].items()
                       if st == export.STATUS_OK})
    truth_da = None
    if ok_leads:
        truth_da, _ = fields.fetch_truth_at(cfg, init_time, ok_leads, variables)

    res = entry["grid"]["resolution_deg"]
    cache: dict = {}

    def lookup(model, var, kind, lead):
        if model not in models:
            return None
        if model not in cache:
            cache[model] = fields.source_arrays(cfg, init_time, model, variables,
                                                leads, res, truth_da, ok_leads)
        return cache[model].get((var, kind, lead))

    return lookup, [m for m in entry["models"] if m not in models]


