def _nudge_one(codes: np.ndarray) -> np.ndarray:
    """Move one byte by two levels.

    Two rather than one: a one-level move can land a cell whose original
    residual sat at exactly -step/2 back on +step/2, i.e. still inside the
    bound, so a self-test built on it would pass or fail by luck.
    """
    out = codes.copy()
    r, c = out.shape[0] // 2, out.shape[1] // 2
    v = int(out[r, c])
    out[r, c] = np.uint8(v - 2 if v > fields.MIN_BYTE + 2 else v + 2)
    return out


def _fill_missing(codes: np.ndarray) -> np.ndarray:
    out = codes.copy()
    out[out == fields.MISSING_BYTE] = 128
    return out


def _blank_one(codes: np.ndarray) -> np.ndarray:
    out = codes.copy()
    out[out.shape[0] // 2, out.shape[1] // 2] = fields.MISSING_BYTE
    return out


