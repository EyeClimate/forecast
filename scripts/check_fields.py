def tree_self_test(manifest_schema: dict) -> list[str]:
    fails = []
    tmp = Path(tempfile.mkdtemp(prefix="check_fields_"))
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            cfg = _synth_site(tmp)
            base, stats = check_tree(tmp / "data", cfg, manifest_schema,
                                     SYNTH_NOW, _synth_provider)
        if base:
            return ["tree self-test: the pristine synthetic tree does not pass "
                    f"its own checks ({base[0]})"]
        if not stats.get("n_decoded"):
            return ["tree self-test: the pristine tree decoded 0 PNG(s) — the "
                    "half-step gate is not running at all"]
        for desc, corrupt in TREE_CORRUPTIONS:
            work = Path(tempfile.mkdtemp(prefix="check_fields_case_"))
            try:
                with contextlib.redirect_stdout(io.StringIO()):
                    shutil.copytree(tmp, work, dirs_exist_ok=True)
                    corrupt(work)
                    errs, _ = check_tree(work / "data", _synth_cfg_for(work),
                                         manifest_schema, SYNTH_NOW,
                                         _synth_provider)
                if not errs:
                    fails.append(f"tree self-test: {desc!r} was ACCEPTED — the "
                                 "gate is not enforcing this")
            except Exception as e:  # noqa: BLE001
                fails.append(f"tree self-test {desc!r}: raised instead of "
                             f"reporting ({type(e).__name__}: {e})")
            finally:
                shutil.rmtree(work, ignore_errors=True)

        # A real-time init whose truth landed days ago and was never re-exported.
        work = Path(tempfile.mkdtemp(prefix="check_fields_stale_"))
        try:
            with contextlib.redirect_stdout(io.StringIO()):
                shutil.copytree(tmp, work, dirs_exist_ok=True)
                # An init three days old whose first lead's truth landed two
                # days ago, exported once as truth_pending and never revisited.
                # Internally consistent: the PNG is genuinely absent and there
                # is genuinely no scale, so only the clock can reveal it.
                for m in SYNTH_MODELS:
                    _png(work, m, "error", 24).unlink()
                stamp = f"{SYNTH_NOW - timedelta(days=3):{export.TIME_FMT}}"
                _edit(work, lambda e: (
                    e.update(regime="realtime", tier="provisional",
                             init_time=stamp),
                    e["variables"]["t2m"]["error"]["status"].update(
                        {"24": "truth_pending"}),
                    e["variables"]["t2m"]["error"]["scales"].pop("24", None)))
                _refresh_bytes(work)
                errs, _ = check_tree(work / "data", _synth_cfg_for(work),
                                     manifest_schema, SYNTH_NOW, _synth_provider)
            if not any("truth_pending" in e and "available since" in e
                       for e in errs):
                fails.append("tree self-test: a real-time init left three days "
                             "behind its available truth was ACCEPTED — nothing "
                             "would ever make its error map complete")
        finally:
            shutil.rmtree(work, ignore_errors=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return fails


def _synth_cfg_for(site: Path) -> dict:
    return {"paths": {"data": str(site / "store"), "site": str(site)},
            "historic_cutoff_days": 120, "retention_days": 30}


def schema_self_test(manifest_schema: dict) -> list[str]:
    """Every mutation of a valid fields section must be rejected."""
    tmp = Path(tempfile.mkdtemp(prefix="check_fields_schema_"))
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            _synth_site(tmp)
        doc = json.loads((tmp / "data" / "manifest.json").read_text())
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return check_export.self_test(doc, manifest_schema, FIELD_SCHEMA_MUTATIONS,
                                  "fields")


