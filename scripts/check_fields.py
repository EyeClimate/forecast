def main() -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default="config.yaml")
    ap.add_argument("--no-source-check", action="store_true",
                    help="skip layer 3 (needs the forecast zarrs and a truth "
                         "fetch). The self-test still exercises it.")
    a = ap.parse_args()
    repo = Path(__file__).resolve().parents[1]
    cfg = yaml.safe_load((repo / a.config).read_text())
    root = repo / cfg["paths"]["site"] / "data"

    manifest_schema = json.loads(
        (root / "schema" / "manifest.schema.json").read_text())
    check_export.assert_supported(manifest_schema, "manifest")
    print(f"[check] validator: {check_export.VALIDATOR}")

    failures: list[str] = []
    provider = None if a.no_source_check else real_source_provider(cfg)
    tree_failures, stats = check_tree(root, cfg, manifest_schema,
                                      export._utcnow(), provider)
    failures += tree_failures
    if not stats:
        print(f"\n[check] FAILED — {failures[0] if failures else 'no stats'}")
        return 1

    for entry in stats["inits"]:
        n = entry["bytes"]
        grid = entry["grid"]
        print(f"[check] {entry['init_time']}  {entry['regime']:<8} "
              f"tier={entry['tier']:<11} "
              f"{len(entry['models'])}/{len(entry['models_expected'])} model(s)  "
              f"{grid['height']}x{grid['width']} @ {grid['resolution_deg']}°  "
              f"{entry['png_count']}/{entry['png_count_when_complete']} PNG(s)  "
              f"{n / 1048576:.2f} MiB "
              f"({100 * n / FIELDS_BUDGET_BYTES:.0f}% of budget)")
        for var, vmeta in entry["variables"].items():
            for h in entry["leads"]:
                fs = vmeta["forecast"]["scales"].get(str(h))
                es = vmeta["error"]["scales"].get(str(h))
                st = vmeta["error"]["status"].get(str(h))
                fstep = fields.quantization_step(fs) if fs else float("nan")
                estep = fields.quantization_step(es) if es else float("nan")
                print(f"[check]     {var} {h:>4} h  forecast "
                      f"[{fs[0]:.2f}, {fs[1]:.2f}] step {fstep:.4f}  "
                      + (f"error [{es[0]:+.3f}, {es[1]:+.3f}] step {estep:.4f}"
                         if es else f"error {st}"))

    for name, gone in stats["unverified"]:
        print(f"[check] {name}: {len(gone)} model(s) cannot be checked against "
              f"a source array — {gone}. Their forecast zarrs are gone; the "
              "PNGs stay valid but unverifiable.")
    if provider is not None and stats["n_decoded"] == 0:
        failures.append(
            "no PNG was decoded against a source array. Every init's forecast "
            "zarr has been swept, so the half-step encoding gate — the check "
            "that makes this export trustworthy — did not run on any real "
            "data. Re-export an init whose zarr survives, or re-forecast one.")
    print(f"[check] decode gate: {stats['n_decoded']} PNG(s) decoded and "
          f"compared against their source arrays"
          + (" (skipped: --no-source-check)" if provider is None else ""))

    schema_fails = schema_self_test(manifest_schema)
    failures += schema_fails
    print(f"[check] schema self-test: {len(FIELD_SCHEMA_MUTATIONS)} mutations"
          f"{'' if not schema_fails else ' — FAILURES BELOW'}, all rejected as "
          "required")

    tree_fails = tree_self_test(manifest_schema)
    failures += tree_fails
    print(f"[check] gate self-test: {len(TREE_CORRUPTIONS)} corrupted tree(s) + "
          f"1 stale init{'' if not tree_fails else ' — FAILURES BELOW'}, all "
          "caught as required (pristine tree passes)")

    if failures:
        print(f"\n[check] FAILED — {len(failures)} problem(s):")
        for f in failures:
            print(f"  - {f}")
        return 1
    total = sum(stats["bytes"].values())
    print(f"\n[check] OK — {stats['n_png']} PNG(s) across "
          f"{len(stats['inits'])} init(s), {total / 1048576:.2f} MiB total")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
