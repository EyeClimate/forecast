#!/usr/bin/env python
"""Validate the gridded field export — docs/data/fields/** and the manifest.

    conda run -n earth2 python scripts/check_fields.py

The gate that makes the encoding trustworthy is layer 3: **every emitted PNG is
decoded back to float through the scale published in `manifest.json` and
compared against the source array, and the maximum absolute difference must be
at most half the quantization step.** Nothing else here can substitute for it.
A scale that is stale, mistyped, off by a factor, or simply attached to the
wrong lead produces a PNG that renders as a perfectly plausible weather map of
the wrong numbers, and the only way to notice is to invert the encoding and
check.

Five layers, mirroring scripts/check_export.py's structure and reusing its
schema validator:

1. **Schema.** `manifest.json` against `docs/data/schema/manifest.schema.json`,
   and every `fields/<init>/index.json` sidecar against that schema's
   `$defs/fieldsInit` — the sidecar and the manifest entry are the same object,
   so one definition governs both.
2. **Structure.** The manifest's `fields` section, the sidecars, and the files
   on disk must agree: which inits exist, which PNGs exist, their dimensions,
   the byte totals, and — the E4-specific invariants — that error scales are
   symmetric about zero, that the reserved missing byte sits outside the data
   range, and that a lead marked `truth_pending` has no PNG while every lead
   marked `ok` has one.
3. **The decode gate**, above. Source arrays are regenerated by calling
   `scoreboard.fields` itself, so the gate tests the pipeline rather than a
   second copy of it. It runs for every init whose forecast zarr survives; an
   init whose zarr sweep.py has purged is reported as unverifiable, and the run
   **fails if no init could be verified at all**, so the gate cannot decay into
   a no-op as retention rolls forward.
4. **Staleness.** A real-time init exported the day it ran has error fields for
   only its first leads. There is no top-up for fields — a re-export is a full
   one — so unless something insists, the map's error view stays frozen at 2 of
   5 leads until the zarr is swept and it can never be completed at all.
5. **The gate itself.** A synthetic tree, corrupted one way at a time, with each
   corruption required to be caught, and schema mutations required to be
   rejected. A check that accepted everything would otherwise look exactly like
   a passing one — and the half-step assertion in particular is easy to write in
   a form that can never fail.
"""

