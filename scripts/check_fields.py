# Layers 2 + 3 over one init entry


def check_init_entry(name: str, entry: dict, root: Path,
                     lookup) -> tuple[list[str], int]:
    """Structure, encoding invariants, and the decode gate. (errors, n decoded).

    `lookup(model, var, kind, lead) -> array | None` supplies source arrays;
    None means unverifiable (the forecast zarr is gone), which is reported by
    the caller rather than treated as a pass.
    """
    errs: list[str] = []
    n_decoded = 0
    d = root / entry["dir"]
    if d.name != name:
        errs.append(f"fields[{name}]: dir {entry['dir']!r} does not end in the "
                    "init stamp it is keyed by")
    if not d.is_dir():
        return errs + [f"fields[{name}]: {d} does not exist"], 0

    enc = entry["encoding"]
    if enc["levels"] != enc["max_byte"] - enc["min_byte"]:
        errs.append(f"fields[{name}]: encoding levels {enc['levels']} != "
                    f"max_byte - min_byte ({enc['max_byte']} - "
                    f"{enc['min_byte']})")
    if enc["min_byte"] <= enc["missing"] <= enc["max_byte"]:
        errs.append(f"fields[{name}]: the reserved missing byte "
                    f"{enc['missing']} lies inside the data range "
                    f"[{enc['min_byte']}, {enc['max_byte']}] — a real value and "
                    "'no data' would encode identically")
    for key, want in (("missing", fields.MISSING_BYTE),
                      ("min_byte", fields.MIN_BYTE),
                      ("max_byte", fields.MAX_BYTE),
                      ("levels", fields.LEVELS)):
        if enc[key] != want:
            errs.append(f"fields[{name}]: encoding.{key} is {enc[key]} but "
                        f"scoreboard.fields encodes with {want}")

    grid = entry["grid"]
    shape = (grid["height"], grid["width"])
    if grid["lat_step"] >= 0:
        errs.append(f"fields[{name}]: lat_step {grid['lat_step']} is not "
                    "negative — the exported grid runs north to south, and a "
                    "renderer trusting this would draw it upside down")
    for axis, start, step, n, span in (
            ("lat", grid["lat_start"], grid["lat_step"], grid["height"], -180.0),
            ("lon", grid["lon_start"], grid["lon_step"], grid["width"], 360.0)):
        covered = step * (n - 1 if axis == "lat" else n)
        if abs(covered - span) > 1e-9:
            errs.append(f"fields[{name}]: {axis} runs {start} by {step} for {n} "
                        f"cells, covering {covered}° rather than {span}°")

    seen: set[Path] = set()
    for var, vmeta in entry["variables"].items():
        for kind, meta in (("forecast", vmeta["forecast"]),
                           ("error", vmeta["error"])):
            scales = meta["scales"]
            status = meta.get("status")
            for h in entry["leads"]:
                key = str(h)
                pending = status is not None and \
                    status.get(key) == export.STATUS_TRUTH_PENDING
                if status is not None and key not in status:
                    errs.append(f"fields[{name}] {var}.{kind}: lead {h} h has no "
                                "status")
                if pending:
                    if key in scales:
                        errs.append(f"fields[{name}] {var}.{kind}: lead {h} h is "
                                    f"{export.STATUS_TRUTH_PENDING} but carries "
                                    "a scale")
                    continue
                if key not in scales:
                    errs.append(f"fields[{name}] {var}.{kind}: lead {h} h has no "
                                "scale in the manifest — it cannot be decoded")
                    continue
                lo, hi = scales[key]
                if not (lo < hi):
                    errs.append(f"fields[{name}] {var}.{kind} lead {h} h: scale "
                                f"[{lo}, {hi}] is not increasing")
                if kind == "error" and lo != -hi:
                    # Exact equality, not a tolerance: the scale is built by
                    # negating one magnitude, so anything else means it was not.
                    errs.append(f"fields[{name}] {var}.error lead {h} h: scale "
                                f"[{lo}, {hi}] is not symmetric about zero — a "
                                "diverging ramp built from it would put its "
                                "neutral colour at "
                                f"{0.5 * (lo + hi):.6g}, misrepresenting the "
                                "sign of a bias")

    for model in entry["models"]:
        for var, vmeta in entry["variables"].items():
            for kind, meta in (("forecast", vmeta["forecast"]),
                               ("error", vmeta["error"])):
                status = meta.get("status")
                for h in entry["leads"]:
                    key = str(h)
                    path = d / model / var / meta["file"].replace("{lead}", key)
                    pending = status is not None and \
                        status.get(key) == export.STATUS_TRUTH_PENDING
                    if pending:
                        if path.exists():
                            errs.append(
                                f"{path.relative_to(root)}: exists although "
                                f"{var}.{kind} lead {h} h is marked "
                                f"{export.STATUS_TRUTH_PENDING}")
                        continue
                    if not path.exists():
                        errs.append(f"fields[{name}]: {path.relative_to(root)} "
                                    f"is missing, but {var}.{kind} lead {h} h is "
                                    f"marked {export.STATUS_OK}")
                        continue
                    seen.add(path)
                    if key not in meta["scales"]:
                        continue
                    codes = fields.read_png(path)
                    if codes.shape != shape:
                        errs.append(f"{path.relative_to(root)}: {codes.shape} "
                                    f"does not match the declared grid {shape}")
                        continue
                    bad = np.unique(codes[(codes != enc["missing"])
                                          & ((codes < enc["min_byte"])
                                             | (codes > enc["max_byte"]))])
                    if bad.size:
                        errs.append(f"{path.relative_to(root)}: byte value(s) "
                                    f"{bad.tolist()} are neither the missing "
                                    "value nor inside the data range")
                    src = lookup(model, var, kind, h) if lookup else None
                    if src is None:
                        continue
                    errs += encoding_errors(str(path.relative_to(root)), codes,
                                            src, meta["scales"][key])
                    n_decoded += 1

    on_disk = {p for p in d.rglob("*.png")}
    orphans = sorted(str(p.relative_to(root)) for p in on_disk - seen)
    if orphans:
        errs.append(f"fields[{name}]: {len(orphans)} PNG(s) on disk that the "
                    f"manifest does not describe — {orphans[:4]}")
    if len(on_disk) != entry["png_count"]:
        errs.append(f"fields[{name}]: png_count {entry['png_count']} != "
                    f"{len(on_disk)} file(s) on disk")
    want_complete = (len(entry["models"]) * len(entry["variables"])
                     * len(entry["leads"]) * 2)
    if entry["png_count_when_complete"] != want_complete:
        errs.append(f"fields[{name}]: png_count_when_complete "
                    f"{entry['png_count_when_complete']} != models x variables "
                    f"x leads x 2 = {want_complete}")
    nbytes = sum(p.stat().st_size for p in on_disk)
    if nbytes != entry["bytes"]:
        errs.append(f"fields[{name}]: bytes {entry['bytes']} != actual {nbytes}")
    if nbytes > FIELDS_BUDGET_BYTES:
        errs.append(f"fields[{name}]: {nbytes / 1048576:.1f} MiB exceeds the "
                    f"{FIELDS_BUDGET_BYTES / 1048576:.0f} MiB per-init budget "
                    "(PLAN_EXPLORER.md §4/§7)")
    return errs, n_decoded


def staleness_errors(name: str, entry: dict, now: datetime) -> list[str]:
    """A lead whose truth has landed but whose error field was never written.

    Unlike points, fields have no incremental top-up: the fix is a full
    re-export, which is only possible while the forecast zarr survives. So an
    init left alone after its first export keeps an error map that stops at
    lead 48 h for the rest of its life.
    """
    errs = []
    init = datetime.strptime(entry["init_time"], export.TIME_FMT)
    leads = entry["leads"]
    through = export.truth_available_through(init, leads, entry["regime"], now)
    if through is None:
        return errs
    cutoff = through - timedelta(hours=TRUTH_STALENESS_GRACE_HOURS)
    for var, vmeta in entry["variables"].items():
        stale = [h for h in leads
                 if vmeta["error"]["status"].get(str(h)) == export.STATUS_TRUTH_PENDING
                 and init + timedelta(hours=h) <= cutoff]
        if stale:
            errs.append(
                f"fields[{name}] {var}: lead(s) {stale} h are marked "
                f"{export.STATUS_TRUTH_PENDING}, but their truth has been "
                f"available since at or before {cutoff:{export.TIME_FMT}}. "
                "Fields are re-exported, not topped up — re-run `python -m "
                f"scoreboard.fields --init {name}` while the forecast zarr "
                "still exists.")
    return errs


def check_tree(root: Path, cfg: dict, manifest_schema: dict, now: datetime,
               source_for=None) -> tuple[list[str], dict]:
    """Layers 1-4 over one docs/data tree. Returns (failures, stats).

    Parameterized by root, cfg, clock and source provider so layer 5 can run the
    identical checks against a synthetic tree. A gate that only ever ran against
    the real tree could not be shown to reject anything.
    """
    failures: list[str] = []
    mpath = root / "manifest.json"
    if not mpath.exists():
        return [f"{mpath} does not exist — run `python -m scoreboard.export`"], {}
    try:
        manifest = json.loads(mpath.read_text())
    except json.JSONDecodeError as e:
        return [f"manifest.json is not valid JSON ({e})"], {}

    bad = schema_errors(manifest, manifest_schema)
    failures += [f"manifest.json {m}" for m in bad]
    if bad:
        return failures, {}

    fields_root = root / "fields"
    dirs = sorted(d.name for d in fields_root.glob("*")
                  if d.is_dir()) if fields_root.exists() else []
    section = manifest["fields"]
    if sorted(section) != dirs:
        failures.append(f"manifest.json: fields lists {sorted(section)} but "
                        f"fields/ holds {dirs}")

    entry_schema = subschema(manifest_schema, "fieldsInit")
    stats = {"n_png": 0, "n_decoded": 0, "unverified": [], "inits": [],
             "bytes": {}}
    for name in sorted(set(section) & set(dirs)):
        entry = section[name]
        # The sidecar is the durable record; the manifest is aggregated from it.
        # They are the same object, so any difference means one of the two was
        # written by something other than the exporter.
        sidecar_path = fields_root / name / "index.json"
        if not sidecar_path.exists():
            failures.append(f"fields[{name}]: no index.json sidecar — the "
                            "manifest's copy cannot be regenerated, and "
                            "`python -m scoreboard.export` would drop this init")
        else:
            sidecar = json.loads(sidecar_path.read_text())
            failures += [f"fields/{name}/index.json {m}"
                         for m in schema_errors(sidecar, entry_schema)]
            if sidecar != entry:
                failures.append(
                    f"fields[{name}]: manifest.json and "
                    f"fields/{name}/index.json disagree. The manifest is "
                    "aggregated from the sidecar by export.write_manifest, so "
                    "one of them was hand-edited or an export was interrupted; "
                    "re-run `python -m scoreboard.export`.")
        entry_bad = schema_errors(entry, entry_schema)
        failures += [f"manifest.json fields[{name}] {m}" for m in entry_bad]
        if entry_bad:
            continue

        lookup, gone = (source_for(name, entry) if source_for else (None, []))
        errs, n_dec = check_init_entry(name, entry, root, lookup)
        failures += errs
        failures += staleness_errors(name, entry, now)
        stats["n_decoded"] += n_dec
        stats["n_png"] += entry["png_count"]
        stats["bytes"][name] = entry["bytes"]
        stats["inits"].append(entry)
        if gone:
            stats["unverified"].append((name, gone))
    return failures, stats


def real_source_provider(cfg: dict):
    def provide(name: str, entry: dict):
        init = datetime.strptime(entry["init_time"], export.TIME_FMT)
        return source_lookup_for_init(cfg, entry, init)
    return provide


# ---------------------------------------------------------------------------
# Layer 5: prove the gate rejects a corrupted export
#
# Synthetic fields, so the self-test runs with no zarrs, no network and no GPU:
# a smooth analytic "forecast" and a smaller analytic "error", plus a patch of
# NaN so the reserved missing byte is exercised rather than assumed.

SYNTH_NOW = datetime(2026, 7, 30, 12)
SYNTH_INIT = datetime(2023, 1, 15, 0)        # historic: truth is complete
SYNTH_NAME = f"{SYNTH_INIT:{export.INIT_FMT}}"
SYNTH_LEADS = [24, 48]
SYNTH_MODELS = ["aurora", "atlas"]
SYNTH_RES = 10.0                             # 19 x 36 — small and fast


def _synth_source(model: str, kind: str, lead: int) -> np.ndarray:
    lat, lon = fields.target_grid(SYNTH_RES)
    la = lat[:, None]
    lo = lon[None, :]
    seed = SYNTH_MODELS.index(model) + lead / 24.0
    if kind == "forecast":
        # Asymmetric in latitude on purpose: a field built only from
        # cos(lat) survives a north-south flip unchanged, which would make
        # the orientation corruption below untestable.
        f = (288.0 + 30.0 * np.cos(np.deg2rad(la)) + 0.25 * la
             + 3.0 * np.sin(np.deg2rad(lo) + seed))
    else:
        f = 2.5 * np.sin(np.deg2rad(2 * la)) * np.cos(np.deg2rad(lo) - seed)
    f = np.broadcast_to(f, (lat.size, lon.size)).astype(np.float64).copy()
    f[0, :3] = np.nan            # a hole, so MISSING_BYTE is really exercised
    return f


def _synth_arrays() -> dict:
    return {(m, "t2m", k, h): _synth_source(m, k, h)
            for m in SYNTH_MODELS for k in ("forecast", "error")
            for h in SYNTH_LEADS}


def _synth_site(site: Path) -> dict:
    """Materialize a pristine, passing tree under `site`. Returns its cfg."""
    arrays = _synth_arrays()
    lat, lon = fields.target_grid(SYNTH_RES)
    root = site / "data"
    d = root / "fields" / SYNTH_NAME
    scales = {}
    for kind in ("forecast", "error"):
        for h in SYNTH_LEADS:
            group = [arrays[(m, "t2m", kind, h)] for m in SYNTH_MODELS]
            scales[(kind, h)] = (fields.forecast_scale(group) if kind == "forecast"
                                 else fields.error_scale(group))
    for m in SYNTH_MODELS:
        for kind in ("forecast", "error"):
            for h in SYNTH_LEADS:
                fields.write_png(
                    d / m / "t2m" / f"{'f' if kind == 'forecast' else 'e'}{h}.png",
                    fields.quantize(arrays[(m, "t2m", kind, h)], scales[(kind, h)]))
    entry = {
        "schema_version": 1,
        "init_time": f"{SYNTH_INIT:{export.TIME_FMT}}",
        "generated": f"{SYNTH_NOW:{export.TIME_FMT}}",
        "regime": "historic", "tier": "final",
        "init_source": "era5_arco", "truth_source": "era5_arco",
        "dir": f"fields/{SYNTH_NAME}",
        "grid": {"resolution_deg": SYNTH_RES, "width": int(lon.size),
                 "height": int(lat.size), "lat_start": 90.0, "lat_step": -SYNTH_RES,
                 "lon_start": 0.0, "lon_step": SYNTH_RES},
        "encoding": {"dtype": "uint8", "missing": fields.MISSING_BYTE,
                     "min_byte": fields.MIN_BYTE, "max_byte": fields.MAX_BYTE,
                     "levels": fields.LEVELS, "decode": "value = scale[0] + ..."},
        "leads": list(SYNTH_LEADS),
        "models": list(SYNTH_MODELS),
        "models_expected": list(SYNTH_MODELS),
        "variables": {"t2m": {
            "units": "K",
            "forecast": {"file": "f{lead}.png",
                         "scales": {str(h): scales[("forecast", h)]
                                    for h in SYNTH_LEADS}},
            "error": {"file": "e{lead}.png", "symmetric": True,
                      "definition": "model - truth", "truth_source": "era5_arco",
                      "scales": {str(h): scales[("error", h)] for h in SYNTH_LEADS},
                      "status": {str(h): "ok" for h in SYNTH_LEADS}},
        }},
        "png_count": len(SYNTH_MODELS) * len(SYNTH_LEADS) * 2,
        "png_count_when_complete": len(SYNTH_MODELS) * len(SYNTH_LEADS) * 2,
        "bytes": sum(p.stat().st_size for p in d.rglob("*.png")),
    }
    (d / "index.json").write_text(json.dumps(entry, indent=1) + "\n")
    manifest = {
        "schema_version": 1,
        "generated": f"{SYNTH_NOW:{export.TIME_FMT}}",
        "series_statuses": ["ok", "no_variable", "truth_pending", "unavailable"],
        "leads": list(SYNTH_LEADS),
        "variables": {"t2m": {"label": "2 m temperature", "units": "K",
                              "kind": "state", "decimals": 2}},
        "cities": [{"id": "alphaville", "name": "Alphaville", "lat": 10.0,
                    "lon": 20.0}],
        "inits": [],
        "fields": {SYNTH_NAME: copy.deepcopy(entry)},
    }
    (root / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    return {"paths": {"data": str(site / "store"), "site": str(site)},
            "historic_cutoff_days": 120, "retention_days": 30}


def _synth_provider(name: str, entry: dict):
    arrays = _synth_arrays()

    def lookup(model, var, kind, lead):
        return arrays.get((model, var, kind, lead))
    return lookup, []


def _edit(site: Path, mutate, sidecar: bool = True) -> None:
    """Apply `mutate` to the manifest entry and, unless told otherwise, to the
    sidecar too — so the corruption is internally consistent and can only be
    caught by decoding, not by cross-referencing the two copies."""
    root = site / "data"
    m = json.loads((root / "manifest.json").read_text())
    mutate(m["fields"][SYNTH_NAME])
    (root / "manifest.json").write_text(json.dumps(m, indent=1) + "\n")
    if sidecar:
        p = root / "fields" / SYNTH_NAME / "index.json"
        s = json.loads(p.read_text())
        mutate(s)
        p.write_text(json.dumps(s, indent=1) + "\n")


def _png(site: Path, model: str, kind: str, lead: int) -> Path:
    return (site / "data" / "fields" / SYNTH_NAME / model / "t2m"
            / f"{'f' if kind == 'forecast' else 'e'}{lead}.png")


def _rewrite_png(site: Path, model: str, kind: str, lead: int, transform) -> None:
    p = _png(site, model, kind, lead)
    codes = fields.read_png(p)
    fields.write_png(p, transform(codes))
    _refresh_bytes(site)


def _refresh_bytes(site: Path) -> None:
    """Reconcile the byte totals, leaving everything else as corrupted.

    The byte count is the one thing a hand-edited tree obviously breaks, so a
    check that reconciles it and stops there would pass every case below.
    """
    d = site / "data" / "fields" / SYNTH_NAME
    n = sum(p.stat().st_size for p in d.rglob("*.png"))
    _edit(site, lambda e: e.update(bytes=n))


def _swap_scales(entry: dict) -> None:
    """Attach each of two leads' scales to the other's PNGs."""
    s = entry["variables"]["t2m"]["forecast"]["scales"]
    s["24"], s["48"] = s["48"], s["24"]


def _shift_scale(entry: dict, kind: str, lead: int, by: float) -> None:
    s = entry["variables"]["t2m"][kind]["scales"][str(lead)]
    entry["variables"]["t2m"][kind]["scales"][str(lead)] = [s[0] + by, s[1] + by]


